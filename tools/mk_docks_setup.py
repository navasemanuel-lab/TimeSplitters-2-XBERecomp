"""Writes src/game/docks_setup.inc: Docks' arcade setup. TimeSplitters 2 PC has none for the map (its level table only has
Chemical Plant's row), so it is Chemical Plant's (src/game/chemical_setup.inc: the header, the 34 pickups, the 42 weapon spots, the
kinds and classes as they are) with the pads of Docks: pad ids are picked among Docks' general pads (type 1) by farthest-point
sampling, so the pickups are spread over the map.   python -I mk_docks_setup.py <pad54.raw (version 2)> <out.inc>"""
import re, struct, sys, os
pads = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(pads) // 4), pads)
P = [w[3 + 8 * i:11 + 8 * i] for i in range(w[1])]
f = lambda v: struct.unpack('<f', struct.pack('<I', v))[0]
cand = [(p[0], f(p[3]), f(p[5])) for p in P if p[1] == 1]
chem = open(os.path.join(os.path.dirname(__file__), '..', 'src', 'game', 'chemical_setup.inc')).read()
def arr(n):
    m = re.search(r'%s\[\d+\] = \{(.*?)\};' % n, chem, re.S); return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
H = arr('kChemHeader'); K = arr('kChemPickups'); Ls = arr('kChemLists')
need = len(K) // 8 + len(Ls) // 5
chosen = [cand[0]]
dist = [((c[1] - cand[0][1]) ** 2 + (c[2] - cand[0][2]) ** 2) for c in cand]
while len(chosen) < need:
    i = max(range(len(cand)), key=lambda j: dist[j]); chosen.append(cand[i])
    dist = [min(dist[j], (cand[j][1] - cand[i][1]) ** 2 + (cand[j][2] - cand[i][2]) ** 2) for j in range(len(cand))]
ids = [c[0] for c in chosen]
npk = len(K) // 8
for i in range(npk): K[8 * i + 6] = ids[i]
for i in range(len(Ls) // 5): Ls[5 * i + 1] = ids[npk + i]
def out(name, v, per):
    s = 'constexpr uint32_t %s[%d] = {\n' % (name, len(v))
    for i in range(0, len(v), per): s += '    ' + ', '.join('0x%X' % x for x in v[i:i + per]) + ',\n'
    return s + '};\n'
open(sys.argv[2], 'w').write("// Docks' arcade setup (generated by tools/mk_docks_setup.py): Chemical Plant's, over Docks' pads; the pointers (header words 5 and 9) are filled in at run time.\n"
    + out('kDocksHeader', H, 10) + out('kDocksPickups', K, 8) + out('kDocksLists', Ls, 5))
print('pads used', len(ids), 'of', len(cand))
