"""Writes src/game/chemical_setup.inc: Chemical Plant's arcade setup from TimeSplitters 2 PC's TS2.exe (data only, the two tables hold pad ids
and the shared object ids: python -I mk_chem_setup.py <TS2.exe> <out.inc>). Header 0xA46978 (50 words), tables 0xA461F0 (34 x 8) and 0xA46630 (42 x 5)."""
import struct, sys
d = open(sys.argv[1], 'rb').read()
sec = [(4096, 5089881, 1024), (5095424, 461968, 5091328), (5558272, 4613860, 5553664)]
def fo(va):
    r = va - 0x400000
    for a, vs, o in sec:
        if a <= r < a + vs: return o + r - a
pc = lambda va, n: struct.unpack('<%dI' % n, d[fo(va):fo(va) + n * 4])
hdr = list(pc(0xA46978, 50)); p1 = pc(0xA461F0, 34 * 8); p3 = pc(0xA46630, 42 * 5)
assert hdr[5] == 0xA461F0 and hdr[9] == 0xA46630
hdr[5] = 0; hdr[9] = 0
def arr(name, v, per):
    s = 'constexpr uint32_t %s[%d] = {\n' % (name, len(v))
    for i in range(0, len(v), per): s += '    ' + ', '.join('0x%X' % x for x in v[i:i + per]) + ',\n'
    return s + '};\n'
open(sys.argv[2], 'w').write("// Chemical Plant's arcade setup (generated by tools/mk_chem_setup.py from TimeSplitters 2 PC's TS2.exe); the pointers (header words 5 and 9) are filled in at run time.\n"
    + arr('kChemHeader', hdr, 10) + arr('kChemPickups', list(p1), 8) + arr('kChemLists', list(p3), 5))
