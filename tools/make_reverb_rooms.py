def mb(x):
    return int(round(2000 * math.log10(max(x, 1e-5))))


def main():
    src, out = sys.argv[1], sys.argv[2]
    levels = {}
    names = set()
    for f in sorted(os.listdir(src)):
        m = re.fullmatch(r'level(\d+)\.reverb', f)
        if not m:
            continue
        rooms = {}
        for line in open(os.path.join(src, f), errors='replace'):
            r = re.match(r'\s*(\d+)\s*:\s*k_rvb_REVERB_PRESET_(\w+)', line)
            if r:
                rooms[int(r.group(1))] = r.group(2)
                names.add(r.group(2))
        levels[int(m.group(1))] = rooms
    order = sorted(names)
    missing = [n for n in order if n not in P]
    assert not missing, missing
    o = ['// generated by tools/make_reverb_rooms.py from the overrides of TimeSplitters Future Perfect PC; do not edit',
         'struct ReverbPreset { int room, reflections, reverb; float decay, hf_ratio, refl_delay, rev_delay; };',
         'static const ReverbPreset kReverbPresets[] = {']
    for n in order:
        g, dec, hf, rg, rd, lg, ld, op = P[n]
        k = 0.5 if op else 1.0
        o.append('    {%d, %d, %d, %.2ff, %.2ff, %.3ff, %.3ff},  // %s' % (mb(g), mb(rg * k), mb(lg * k), dec, hf, rd, ld, n))
    o.append('};')
    for lv, rooms in sorted(levels.items()):
        top = max(rooms) + 1
        o.append('static const uint8_t kReverbLevel%d[] = {%s};' % (
            lv, ','.join(str(order.index(rooms[i]) + 1 if i in rooms else 0) for i in range(top))))
    o.append('struct ReverbLevel { int level; const uint8_t* rooms; int count; };')
    o.append('static const ReverbLevel kReverbLevels[] = {')
    for lv in sorted(levels):
        o.append('    {%d, kReverbLevel%d, int(sizeof(kReverbLevel%d))},' % (lv, lv, lv))
    o.append('};')
    open(out, 'w').write('\n'.join(o) + '\n')
    print(len(levels), 'levels', len(order), 'presets')


main()
